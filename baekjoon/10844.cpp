#include <iostream>
#include <vector>
#include <algorithm>

using namespace std;

int main(void)
{
    int n;
    cin>>n;
        
    long long dp[100][10];
    dp[0][0]=0;
    fill(dp[0]+1, dp[0]+10, 1);

    for(int i=1; i<n; i++)
    {
        dp[i][0] = dp[i-1][1]%1000000000;
        dp[i][9] = dp[i-1][8]%1000000000;
        for(int j=1; j<9; j++)
            dp[i][j] = (dp[i-1][j-1]+dp[i-1][j+1])%1000000000;
    }

    long long total=0;
    for(int i=0; i<10; i++)
        total+=dp[n-1][i];
        
    cout<<total%1000000000;

    return 0;
}

